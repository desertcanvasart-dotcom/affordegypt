// Wipe `entrance_fees` and reload it from an operator-provided CSV of
// FINAL per-person prices (no markup math — the CSV already holds the
// price customers pay).
//
// Input CSV columns:
//   name, city, price_per_person, student_price, notes
//
// Row encoding mirrors the admin route (server/admin-catalog-routes.ts):
//   city              = city.toLowerCase()            (stored as-is, not slugified)
//   slug              = `${slugify(city)}-${slugify(name)}`
//   name_translations = { en: name }
//   base_price        = price_per_person              (mirrored; legacy notNull col)
//   markup_percent    = 0
//   price_per_person  = price_per_person
//   currency          = EGP
//   notes             = "Student: N EGP" [+ " | " + free-text note]
//   is_active         = true
//   sort_order        = 10, 20, 30, …  (CSV order)
//
// Output (no DB writes): a single-transaction SQL file
//   migrations-adhoc/entrance-fees-override-2026-07-01.sql
//   (BEGIN; TRUNCATE … RESTART IDENTITY; INSERT …; COMMIT;)
//
// Run:  node scripts/override-entrance-fees-from-csv.mjs "<path-to.csv>"

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import csv from "csv-parser";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const CSV_PATH = process.argv[2];
const OUT_PATH = path.join(REPO_ROOT, "migrations-adhoc", "entrance-fees-override-2026-07-01.sql");

if (!CSV_PATH || !fs.existsSync(CSV_PATH)) {
  console.error(`CSV not found. Usage: node scripts/override-entrance-fees-from-csv.mjs "<path-to.csv>"`);
  process.exit(1);
}

// Same slugify as server/admin-catalog-routes.ts efSlugify.
const slugify = (s) =>
  String(s).toLowerCase().normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .replace(/['"`]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

// Parse a price that may be quoted with a thousands separator ("1,640").
const parsePrice = (raw) => {
  const n = Number(String(raw ?? "").replace(/,/g, "").trim());
  return Number.isFinite(n) && n > 0 ? n : null;
};

const buildNotes = (studentPrice, freeNote) => {
  const parts = [];
  if (studentPrice != null) parts.push(`Student: ${studentPrice} EGP`);
  const note = String(freeNote ?? "").trim();
  if (note) parts.push(note);
  return parts.length ? parts.join(" | ") : null;
};

const sqlEscape = (s) => String(s ?? "").replace(/'/g, "''");

const readCsv = () =>
  new Promise((resolve, reject) => {
    const rows = [];
    fs.createReadStream(CSV_PATH)
      .pipe(csv())
      .on("data", (r) => rows.push(r))
      .on("end", () => resolve(rows))
      .on("error", reject);
  });

const rows = await readCsv();
const accepted = [];
const skipped = [];
const seenSlugs = new Map();

for (let i = 0; i < rows.length; i++) {
  const r = rows[i];
  const name = String(r.name ?? "").trim();
  const city = String(r.city ?? "").trim().toLowerCase();
  const ctx = `row${i + 2} "${name}" (${city})`;

  if (!name || !city) { skipped.push(`${ctx}: missing name or city`); continue; }

  const price = parsePrice(r.price_per_person);
  if (price == null) { skipped.push(`${ctx}: bad price_per_person "${r.price_per_person}"`); continue; }
  const studentPrice = parsePrice(r.student_price); // null if empty/invalid — allowed

  const slug = `${slugify(city)}-${slugify(name)}`;
  if (seenSlugs.has(slug)) {
    skipped.push(`${ctx}: DUPLICATE slug "${slug}" (first at row${seenSlugs.get(slug) + 2})`);
    continue;
  }
  seenSlugs.set(slug, i);

  accepted.push({ slug, city, name, price, notes: buildNotes(studentPrice, r.notes) });
}

const lines = [];
lines.push("-- Auto-generated by scripts/override-entrance-fees-from-csv.mjs");
lines.push(`-- Source CSV: ${path.basename(CSV_PATH)}`);
lines.push(`-- Date: 2026-07-01   Rows: ${accepted.length} accepted, ${skipped.length} skipped`);
lines.push("-- Prices are FINAL per-person (no markup). Wipes and reloads entrance_fees.");
lines.push("");
lines.push("BEGIN;");
lines.push("TRUNCATE entrance_fees RESTART IDENTITY;");
lines.push("");
let sortOrder = 10;
for (const a of accepted) {
  const nameTr = JSON.stringify({ en: a.name });
  lines.push(
    `INSERT INTO entrance_fees (slug, name_translations, city, base_price, markup_percent, price_per_person, currency, notes, is_active, sort_order) VALUES (` +
      `'${sqlEscape(a.slug)}', '${sqlEscape(nameTr)}'::jsonb, '${sqlEscape(a.city)}', ` +
      `${a.price}, 0, ${a.price}, 'EGP', ${a.notes ? `'${sqlEscape(a.notes)}'` : "NULL"}, true, ${sortOrder});`
  );
  sortOrder += 10;
}
lines.push("");
lines.push("COMMIT;");
lines.push("");

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, lines.join("\n"), "utf8");

console.log(`Wrote ${OUT_PATH}`);
console.log(`Accepted: ${accepted.length}   Skipped: ${skipped.length}`);
const perCity = {};
for (const a of accepted) perCity[a.city] = (perCity[a.city] ?? 0) + 1;
console.log("Per-city:");
for (const [c, n] of Object.entries(perCity).sort()) console.log(`  ${c.padEnd(18)} ${n}`);
if (skipped.length) {
  console.log("\nSkipped:");
  for (const s of skipped) console.log(`  ${s}`);
}
